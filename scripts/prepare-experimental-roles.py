"""Extract declared troop roles from the exact scripts build used by the captures.

This reads compiled declarations only; it does not execute Warband bytecode or
claim to recover dynamic troop-slot changes. No module/recorder files are edited.
"""
import argparse
import hashlib
import json
from pathlib import Path

EXPECTED = '5b2c26a28ab972460acfb7ff63b4193cd2d2619bad04b4892ac43d85cc1ada02'

def extract(raw):
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED:
        raise ValueError('Unreviewed scripts build; refusing to infer its class semantics')
    lines = raw.decode().splitlines()
    index = next(i for i, line in enumerate(lines) if line.startswith('multiplayer_get_troop_class '))
    words = list(map(int, lines[index + 1].split()))
    count, offset, operations = words[0], 1, []
    for _ in range(count):
        op, size = words[offset:offset + 2]
        operations.append((op, words[offset + 2:offset + 2 + size]))
        offset += 2 + size
    assert offset == len(words)
    branches, branch, started, skipped = [], [], False, 0
    for op, args in operations:
        if not started:
            if op == 4:
                started = True
            continue
        if op in (3, 5):
            branches.append(branch)
            branch = []
            if op == 3:
                break
        else:
            assert op == 2133 or op & 0x3fffffff in (31, 33)
            branch.append((op, args))
    declarations = []
    for branch in branches:
        positive, excluded, role = [], [], None
        for op, args in branch:
            if op == 2133:
                value = args[1]
                role = 'cavalry' if 14 <= value <= 19 else 'artillery' if value in (20, 21) else 'infantry' if value in (10, 11, 12, 13, 22, 23) else None
                continue
            base = op & 0x3fffffff
            if len(args) != (2 if base == 31 else 3):
                # One malformed one-operand equality does not declare a troop ID.
                skipped += 1
                continue
            assert args[0] == 1224979098644774912
            assert all(0 <= value < 100000 for value in args[1:])
            ids = {args[1]} if base == 31 else set(range(args[1], args[2]))
            (excluded if op & 0x80000000 else positive).append(ids)
        if role:
            declarations.append((set().union(*positive) - set().union(*excluded), role))
    candidates = {}
    for ids, role in declarations:
        for troop in ids:
            candidates.setdefault(troop, set()).add(role)
    # Conflicting category declarations remain unknown rather than guessed.
    roles = {str(troop): next(iter(values)) for troop, values in sorted(candidates.items()) if len(values) == 1}
    return {'scripts_sha256': digest, 'source_script': 'multiplayer_get_troop_class',
            'semantics': 'build-matched declared roles, not captured runtime slots',
            'skipped_incomplete_conditions': skipped, 'roles': roles}

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('scripts', type=Path)
    parser.add_argument('--output', type=Path, default=Path('src/experimental-replay-roles.js'))
    args = parser.parse_args()
    catalog = extract(args.scripts.read_bytes())
    args.output.write_text('// Generated by scripts/prepare-experimental-roles.py; do not infer player names.\nexport default ' + json.dumps(catalog, indent=2) + ';\n')
    print(f"Wrote {len(catalog['roles'])} declared troop roles, gated by scripts SHA-256.")
